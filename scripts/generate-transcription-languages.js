import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const openApiPath = resolve(projectRoot, 'openapi/openapi.yaml');
const outputPath = resolve(projectRoot, 'src/generated/transcriptionLanguages.ts');
const document = parse(readFileSync(openApiPath, 'utf8'));
const languages = document.components?.parameters?.TranscriptionLanguage?.schema?.enum;

if (
  !Array.isArray(languages) ||
  languages.length === 0 ||
  !languages.every((language) => typeof language === 'string') ||
  new Set(languages).size !== languages.length
) {
  throw new Error('OpenAPI TranscriptionLanguage enum must contain unique string values');
}

const source = `/**
 * Generated from openapi/openapi.yaml by scripts/generate-transcription-languages.js.
 * Do not edit this file directly.
 */
export const TRANSCRIPTION_LANGUAGES = ${JSON.stringify(languages, null, 2)} as const;

export type TranscriptionLanguage = (typeof TRANSCRIPTION_LANGUAGES)[number];
`;

mkdirSync(dirname(outputPath), { recursive: true });
writeFileSync(outputPath, source);
